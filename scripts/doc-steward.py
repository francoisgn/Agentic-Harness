#!/usr/bin/env python3
"""Deterministic half of the doc steward (STEWARDS.md §2; standard library only): decides, files issues, writes text.

Subcommands, called by doc-steward.yml (the agent only starts when `pending` says there is something to fold):
  fold-guard  one fold at a time, on one branch (CONVENTIONS.md §Ledger): refused while a PR from the steward's branch
           is open (its link is printed), or when `--head-branch` is another branch. Also called by `pending` and before
           the push; a project's own fold command can call it first. Exit 0 free, 1 refused, 2 could not check.
  pending  anything to fold since the last pass? Refused (`open_fold`, nothing else read) while a fold PR is open. The last pass is the last merged PR from the steward's branch: its
           body carries `Steward-Through: <time>`, `Folded: #a #b` and `Pending entries: #a #b #c.`. The `### Ledger`
           section is the entry (CONVENTIONS.md §Ledger), no label is needed from the author. Pending ledger: PRs
           merged into the base since then whose section has entry blocks (minus those marked `<label>: done`), the
           entries the last pass did not fold, and, as a hint, merged PRs still carrying the ledger label. Malformed
           entries are reported (`malformed`), never skipped silently. `mark_done`: the PRs the last steward PR
           folded that do not carry `<label>: done` yet (the workflow sets it, the steward's only label). Docs: PRs
           merged since then whose `Docs:` line names files (`Docs: none (…)` and a missing line ask for nothing).
           First pass: the last `--since-days` days. Writes a JSON report (`fold`, `since`, `through`, `ledger`,
           `ledger_order` (merge order, for "first merged wins"), `malformed`, `docs`, `mark_done`).
  body     the body of the steward's draft docs PR from that report: the markers, the PRs handled, the output of
           the fold command, then two sections: contested entries (`--contested`, the JSON lines the fold command
           wrote to $STEWARD_CONTESTED, both texts quoted) and unplaced entries (left in place, never dropped).
  note     folds one `note` entry (text outside the tables): first line `<file>` or `<file> § <heading>`, then the
           text, appended at the end of that section (or of the file); already there = nothing changes. Exit 0
           placed, 1 unplaced (the reason on one line, for the fold command's unplaced list).
  audit    weekly safety net: one issue per gap found by the deterministic checks (`--report NAME=FILE`, the output
           of a failed check: readme, links, diagrams, progress), none for a gap that already has an open issue
           (same title); at most MAX_ISSUES per run.
Usage: doc-steward.py pending --repo o/r --base develop [--branch docs/steward] [--ledger-label ledger]
                              [--since-days 7] [--protected "main master develop beta"] [--json-out f]
       doc-steward.py fold-guard --repo o/r [--branch docs/steward] [--head-branch "$(git branch --show-current)"]
       doc-steward.py body --pending f [--folded f] [--fold-log f] [--unplaced f] [--contested f]
       doc-steward.py note --entry f|- [--root .]
       doc-steward.py audit --repo o/r --report readme=f [--report links=f …] [--label "type: docs"] [--dry-run]
Exit codes: 0 done (whatever the decision); 1 refused (fold-guard) or unplaced (note); 2 nothing decided: no
token, API error, the branch is protected.
Token: GH_TOKEN (or GITHUB_TOKEN): read pull requests and issues; `audit` also writes issues.
API (REST, 2022-11-28): GET /repos/{o}/{r}/pulls (state, head, base, sort), GET and POST /repos/{o}/{r}/issues,
GET /repos/{o}/{r}/issues/{n} (docs.github.com/en/rest/pulls/pulls, /rest/issues/issues).
"""
import argparse
import datetime
import json
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request

API = "https://api.github.com"
PER_PAGE = 100
MAX_PAGES = 20      # 2,000 items per list: a bound, so a misbehaving API cannot loop forever
MAX_ISSUES = 10     # issues filed per audit run: a broken check must not flood the tracker
MAX_DOCS = 20       # paths read from one `Docs:` line, like pr-hygiene.yml
TITLE_MAX = 240
FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_\n"
DOCS_LINE = re.compile(r"^\s*(?:[-*]\s+)?Docs:[ \t]*(.*)$", re.I)
FENCE = re.compile(r"^\s*(```+|~~~+)(\S*)")
THROUGH = re.compile(r"^\s*Steward-Through:\s*(\S+)", re.M)
FOLDED = re.compile(r"^\s*Folded:\s*(.*)$", re.M)
PENDING = re.compile(r"^\s*Pending entries:\s*(.*)$", re.M)
NONE_LINE = re.compile(r"^\s*(?:[-*]\s+)?None\b(.*)$", re.I)
SECTION_END = re.compile(r"^#{1,3}\s")
LEDGER_FORMAT = ("expected: one fenced block per entry whose language is the entry type (```changelog … ```), "
                 "or the line `None (<reason>)` when the PR has no entry")
NOTE_TARGET = re.compile(r"^\s*(\S+)\s*(?:§\s*(.*?))?\s*$")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
REPRODUCE = {"readme": "python3 .harness/scripts/readme-check.py",
             "links": "python3 .harness/scripts/doc-links.py",
             "diagrams": "python3 .harness/scripts/diagrams-render.py --check",
             "progress": "python3 .harness/scripts/readme-progress.py --check"}


class FetchError(Exception):
    """The API could not be read or written (network, HTTP error, invalid JSON): nothing is decided."""


def github(token):
    """HTTP function `http(path, data=None) -> JSON` on the GitHub REST API; POST when `data` (the tests inject theirs)."""
    def http(path, data=None):
        req = urllib.request.Request(API + path, data=None if data is None else json.dumps(data).encode(),
                                     method="GET" if data is None else "POST",
                                     headers={"Authorization": f"Bearer {token}",
                                              "Accept": "application/vnd.github+json",
                                              "X-GitHub-Api-Version": "2022-11-28",
                                              "User-Agent": "belayline-doc-steward"})
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except (urllib.error.URLError, OSError, ValueError) as e:
            raise FetchError(f"{path.split('?')[0]}: {e}") from e
    return http


def paginate(http, path, stop=None):
    """Every item of a list endpoint; `stop(page)` true ends the walk after that page."""
    items = []
    for page in range(1, MAX_PAGES + 1):
        batch = http(f"{path}&page={page}")
        if not isinstance(batch, list):
            raise FetchError(f"{path.split('?')[0]}: a list was expected")
        items.extend(batch)
        if len(batch) < PER_PAGE or (stop and stop(batch)):
            break
    return items


def parse_time(text):
    return datetime.datetime.fromisoformat(text.replace("Z", "+00:00"))


def iso(moment):
    return moment.astimezone(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _visible_lines(body):
    """Lines of a PR body outside HTML comments and fenced blocks, with the fence state."""
    lines, fence = [], None
    for line in re.sub(r"<!--[\s\S]*?-->", "", body or "").splitlines():
        m = FENCE.match(line)
        if fence:
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) and not m.group(2):
                fence = None
            continue
        if m:
            fence = m.group(1)
            continue
        lines.append(line)
    return lines


def docs_files(body, ledger_heading=None):
    """Files named by the `Docs:` line: a list, [] for `Docs: none (…)`, None without a line.
    With a ledger heading, the line is read in that section (to the next heading of level 1 to 3) when it exists."""
    lines = _visible_lines(body)
    if ledger_heading:
        heading = ledger_heading.strip().lower()
        at = next((i for i, line in enumerate(lines) if line.strip().lower() == heading), None)
        if at is not None:
            section = []
            for line in lines[at + 1:]:
                if re.match(r"^#{1,3}\s", line):
                    break
                section.append(line)
            lines = section
    match = next((m for m in map(DOCS_LINE.match, lines) if m), None)
    if match is None:
        return None
    value = match.group(1).strip()
    if re.match(r"^none\b", value, re.I):
        return []
    value = re.sub(r"\[[^\]]*\]\(([^)]*)\)", r"\1", value).replace("`", "")
    return [p for p in re.split(r"[,\s]+", value) if p][:MAX_DOCS]


def ledger_section(body, heading="### Ledger"):
    """The `### Ledger` section of a PR body (to the next heading of level 1 to 3, outside fenced blocks and HTML
    comments): `present`, `entries` (fenced blocks with a type) and `problems` (malformed entries, each quoting the
    entry and the expected format). An explicit empty section is the line `None (<reason>)`."""
    lines = re.sub(r"<!--[\s\S]*?-->", "", body or "").splitlines()
    wanted = heading.strip().lower()
    at = next((i for i, line in enumerate(lines) if line.strip().lower() == wanted), None)
    result = {"present": at is not None, "entries": 0, "problems": []}
    if at is None:
        return result
    fence, kind, first, none = None, "", None, None
    for line in lines[at + 1:]:
        m = FENCE.match(line)
        if fence:
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) and not m.group(2):
                if kind:
                    result["entries"] += 1
                else:
                    result["problems"].append(f"block without an entry type (`{fence}` then "
                                              f"\"{(first or '').strip()[:80]}\"); {LEDGER_FORMAT}")
                fence = None
            elif first is None:
                first = line
            continue
        if m:
            fence, kind, first = m.group(1), m.group(2), None
            continue
        if SECTION_END.match(line):
            break
        n = NONE_LINE.match(line)
        if n and none is None:
            none = n.group(1)
    if fence:
        result["problems"].append(f"block `{fence}{kind}` not closed (\"{(first or '').strip()[:80]}\"); {LEDGER_FORMAT}")
    if none is not None:
        if not re.match(r"^\s*\(\s*\S[^)]*\)", none):
            result["problems"].append(f"`None` without a reason; {LEDGER_FORMAT}")
        elif result["entries"]:
            result["problems"].append(f"`None (…)` next to entry blocks; {LEDGER_FORMAT}")
    return result


def markers(body):
    """(`Steward-Through` value or None, PR numbers of the `Folded:` line) of a steward PR body."""
    through = THROUGH.search(body or "")
    folded = FOLDED.search(body or "")
    numbers = [int(n) for n in re.findall(r"#(\d+)", folded.group(1))] if folded else []
    return (through.group(1) if through else None), numbers


def pending(repo, base, branch, ledger_label, http, now=None, since_days=7, ledger_heading="### Ledger"):
    """What the steward has to fold since its last merged PR (see the module docstring)."""
    now = now or datetime.datetime.now(datetime.timezone.utc)
    owner = repo.split("/")[0]
    q = urllib.parse.quote
    steward_prs = http(f"/repos/{repo}/pulls?state=closed&head={q(owner + ':' + branch, safe='')}"
                       f"&per_page={PER_PAGE}&page=1")
    if not isinstance(steward_prs, list):
        raise FetchError("steward PRs: a list was expected")
    merged_steward = sorted((p for p in steward_prs if p.get("merged_at")), key=lambda p: p["merged_at"])
    folded, carried = [], set()
    if merged_steward:
        last = merged_steward[-1]
        through, folded = markers(last.get("body"))
        since = parse_time(through or last["merged_at"])
        left = PENDING.search(last.get("body") or "")
        carried = {int(n) for n in re.findall(r"#(\d+)", left.group(1))} - set(folded) if left else set()
    else:
        since = now - datetime.timedelta(days=since_days)

    def older(page):
        return any(parse_time(p.get("updated_at") or p.get("merged_at") or iso(now)) < since for p in page)

    merged = paginate(http, f"/repos/{repo}/pulls?state=closed&base={q(base, safe='')}&sort=updated"
                            f"&direction=desc&per_page={PER_PAGE}", stop=older)
    heading = ledger_heading if ledger_label else None
    done = f"{ledger_label}: done"
    docs, through, sections, malformed, merged_at_of = [], since, set(), [], {}
    for p in merged:
        if not p.get("merged_at") or (p.get("head") or {}).get("ref") == branch:
            continue
        merged_at = parse_time(p["merged_at"])
        if merged_at <= since:
            continue
        through = max(through, merged_at)
        merged_at_of[p["number"]] = p["merged_at"]
        files = docs_files(p.get("body"), heading)
        if files:
            docs.append({"number": p["number"], "title": p.get("title", ""), "files": files})
        if ledger_label and done not in {(lab or {}).get("name") for lab in p.get("labels") or []}:
            section = ledger_section(p.get("body"), ledger_heading)
            if section["entries"]:
                sections.add(p["number"])
            if section["problems"]:
                malformed.append({"number": p["number"], "title": p.get("title", ""), "problems": section["problems"]})
    docs.sort(key=lambda d: d["number"])

    ledger, mark_done = [], []
    if ledger_label:
        # The label is only a hint now (projects that still set it); the section decides.
        issues = paginate(http, f"/repos/{repo}/issues?state=closed&labels={q(ledger_label, safe='')}"
                                f"&per_page={PER_PAGE}")
        labelled = {i["number"] for i in issues if (i.get("pull_request") or {}).get("merged_at")}
        for i in issues:
            merged_at_of.setdefault(i["number"], (i.get("pull_request") or {}).get("merged_at") or "")
        for n in folded[:MAX_PAGES * PER_PAGE]:
            item = http(f"/repos/{repo}/issues/{n}")
            if not isinstance(item, dict):
                raise FetchError(f"/repos/{repo}/issues/{n}: an object was expected")
            names = {(lab or {}).get("name") for lab in item.get("labels") or []}
            if done not in names or ledger_label in names:
                mark_done.append(n)
        ledger = sorted((labelled | sections | carried) - set(folded))
    malformed.sort(key=lambda m: m["number"])
    # "First merged wins" (CONVENTIONS.md §Ledger): the fold command gets the entries in merge order; those carried
    # from the last pass merged before it, so they come first.
    order = sorted(ledger, key=lambda n: (parse_time(merged_at_of[n]) if merged_at_of.get(n) else since, n))
    return {"fold": bool(docs or ledger or malformed), "since": iso(since), "through": iso(through),
            "ledger": ledger, "ledger_order": order, "malformed": malformed, "docs": docs,
            "mark_done": sorted(set(mark_done))}


def open_fold(repo, branch, http):
    """The open PR from the steward's branch ({number, url}), or None: while it is open, no second fold starts."""
    owner = repo.split("/")[0]
    prs = http(f"/repos/{repo}/pulls?state=open&head={urllib.parse.quote(owner + ':' + branch, safe='')}"
               f"&per_page={PER_PAGE}&page=1")
    if not isinstance(prs, list):
        raise FetchError("open steward PRs: a list was expected")
    if not prs:
        return None
    first = min(prs, key=lambda p: p.get("number", 0))
    return {"number": first.get("number"), "url": first.get("html_url", "")}


def contested_lines(text):
    """List items for the contested entries the fold command reported (one JSON object per line: `place`, `first`,
    `first_text`, `second`, `second_text`); a line that cannot be read is kept verbatim, never dropped."""
    def quoted(label, value):
        block = str(value if value is not None else "").replace("```", "'''").rstrip() or "(empty)"
        return [f"  - {label}:", "", "    ```text", *[f"    {line}" for line in block.splitlines()], "    ```", ""]

    items = []
    for raw in (text or "").splitlines():
        if not raw.strip():
            continue
        try:
            entry = json.loads(raw)
            first, second = int(entry["first"]), int(entry["second"])
        except (ValueError, TypeError, KeyError):
            items += [f"- unreadable contested report, kept as written: {raw.strip()}", ""]
            continue
        items += [f"- {entry.get('place') or '(place not given)'}: contested: #{first} vs #{second}. #{first} merged "
                  f"first and is folded; #{second} is reported here: settle it in this PR before merging.", ""]
        items += quoted(f"#{first} (folded)", entry.get("first_text")) + quoted(f"#{second} (reported)",
                                                                                entry.get("second_text"))
    return items


def place_note(text, heading, note):
    """`text` with `note` appended at the end of the section `heading` (to the next heading of the same or a higher
    level), or at the end of the file without a heading. Already present: unchanged. ValueError: heading missing."""
    note = note.strip()
    if note in text:
        return text
    lines = text.splitlines()
    end = len(lines)
    if heading:
        wanted = heading.strip().lower()
        at = next((i for i, line in enumerate(lines)
                   if (m := HEADING.match(line)) and m.group(2).strip().lower() == wanted), None)
        if at is None:
            raise ValueError(f"no heading \"{heading}\"")
        level = len(HEADING.match(lines[at]).group(1))
        end = next((i for i in range(at + 1, len(lines))
                    if (m := HEADING.match(lines[i])) and len(m.group(1)) <= level), len(lines))
    before = lines[:end]
    while before and not before[-1].strip():
        before.pop()
    after = lines[end:]
    return "\n".join(before + ["", *note.splitlines()] + ([""] + after if after else [])) + "\n"


def fold_note(entry, root="."):
    """Folds one `note` entry under `root`; returns (True, message) or (False, why it stays unplaced)."""
    head, _, note = (entry or "").partition("\n")
    m = NOTE_TARGET.match(head)
    if not m or not note.strip():
        return False, "unplaced note: expected a first line `<file>` or `<file> § <heading>`, then the text"
    path, heading = m.group(1), m.group(2) or None
    parts = path.replace("\\", "/").split("/")
    if path.startswith("/") or ".." in parts or parts[0] in (".github", ".harness"):
        return False, f"unplaced note: {path} is outside the files a fold may write"
    target = os.path.join(root, *parts)
    try:
        with open(target, encoding="utf-8") as f:
            text = f.read()
        new = place_note(text, heading, note)
    except OSError as e:
        return False, f"unplaced note: {path}: {e.strerror or e}"
    except ValueError as e:
        return False, f"unplaced note: {path}: {e}"
    if new != text:
        with open(target, "w", encoding="utf-8") as f:
            f.write(new)
    return True, f"note folded in {path}" + (f" § {heading}" if heading else "")


def body(result, folded=None, fold_log="", unplaced="", contested=""):
    """Body of the steward's draft docs PR; the two marker lines are read back by the next pass."""
    ledger = result.get("ledger", [])
    folded = ledger if folded is None else [n for n in folded if n in ledger]
    lines = ["Docs upkeep by the doc steward at merge time (STEWARDS.md §2), rebuilt from the integration branch at",
             "every pass. The \"Fold the ledger\" commit is reproduced by the command in its message, on the base",
             "(CONVENTIONS.md §Ledger); the other commits (docs named by the `Docs:` lines, README progress block)",
             "are reviewed like any change.", "",
             f"Steward-Through: {result.get('through', '')}",
             "Folded: " + (" ".join(f"#{n}" for n in folded) if folded else "none"), "",
             "## Merged PRs whose docs were updated", ""]
    lines += [f"- #{d['number']} {d.get('title', '')}: {', '.join(d['files'])}" for d in result.get("docs", [])] or ["None."]
    lines += ["", "## Ledger fold", ""]
    if ledger:
        lines += ["Pending entries: " + " ".join(f"#{n}" for n in ledger) + ".", "", "```text",
                  (fold_log or "(no output)").replace("```", "'''").rstrip(), "```"]
    else:
        lines.append("Nothing to fold.")
    lines += ["", "## Contested entries", "",
              "Two entries of this pass target the same place: the first merged wins, the other is quoted here",
              "with both texts, never dropped (CONVENTIONS.md §Ledger):", ""]
    lines += contested_lines(contested) or ["None.", ""]
    lines += ["## Unplaced entries", "",
              "What the steward could not place is left in place in its PR and listed here, never dropped:", ""]
    left = [f"- #{n}: ledger entry not folded (see the fold output); it stays in its PR" for n in ledger
            if n not in folded]
    left += [f"- #{m['number']}: malformed ledger entry, the author fixes the PR body: {problem}"
             for m in result.get("malformed", []) for problem in m.get("problems", [])]
    if unplaced and unplaced.strip():
        left.append(unplaced.strip())
    lines += left or ["None."]
    lines += ["", "Direct-PR: docs upkeep", "Docs: none (this PR is the doc update)", "", FOOTER]
    return "\n".join(lines)


def gaps(reports):
    """(check, gap) pairs from the outputs of failed checks: one per `✘` line (one per broken link for `links`,
    one for the whole `progress` diff); a failed check whose output has no such line counts as one gap."""
    found = []
    for check, text in reports.items():
        lines = [line.strip() for line in (text or "").splitlines() if line.strip()]
        if not lines:
            continue
        if check == "progress":
            items = ["README progress block differs from the issues"]
        elif check == "links":
            items = [line for line in lines if not re.match(r"^\d+ broken link", line)]
        else:
            items = [line[1:].strip() for line in lines if line.startswith("✘")]
        found += [(check, item) for item in (items or lines[:1])]
    return found


def audit(repo, reports, label, http, dry_run=False, out=sys.stdout):
    """Files one issue per new gap; returns how many were (or, with dry_run, would be) filed."""
    q = urllib.parse.quote
    query = f"&labels={q(label, safe='')}" if label else ""
    known = {i.get("title") for i in paginate(http, f"/repos/{repo}/issues?state=open{query}&per_page={PER_PAGE}")}
    todo = []
    for check, gap in gaps(reports):
        title = f"Doc audit ({check}): {gap}"[:TITLE_MAX]
        if title in known or title in (t for t, _ in todo):
            print(f"= {title} (open issue already)", file=out)
            continue
        todo.append((title, check))
    for title, check in todo[:MAX_ISSUES]:
        text = (f"The weekly doc audit (STEWARDS.md §2) found this gap with the `{check}` check.\n\n"
                f"Reproduce: `{REPRODUCE.get(check, check)}`\n\n"
                "Fix the doc, or the code if the code is at fault, then close this issue.\n\n" + FOOTER)
        if not dry_run:
            http(f"/repos/{repo}/issues", {"title": title, "body": text, "labels": [label] if label else []})
        print(f"{'would file' if dry_run else '+'} {title}", file=out)
    if len(todo) > MAX_ISSUES:
        print(f"⚠ {len(todo) - MAX_ISSUES} more gap(s) not filed (cap {MAX_ISSUES} per run): see the job log",
              file=out)
    return min(len(todo), MAX_ISSUES)


def _read(path):
    if not path:
        return ""
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError:
        return ""


def run(argv=None, http=None, env=None, out=sys.stdout):
    env = os.environ if env is None else env
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("pending")
    p.add_argument("--repo", default=env.get("GITHUB_REPOSITORY"))
    p.add_argument("--base", required=True)
    p.add_argument("--branch", default="docs/steward")
    p.add_argument("--ledger-label", default="")
    p.add_argument("--ledger-heading", default="### Ledger")
    p.add_argument("--since-days", type=int, default=7)
    p.add_argument("--protected", default="main master develop beta")
    p.add_argument("--json-out")
    b = sub.add_parser("body")
    b.add_argument("--pending", required=True)
    b.add_argument("--folded")
    b.add_argument("--fold-log")
    b.add_argument("--unplaced")
    b.add_argument("--contested")
    g = sub.add_parser("fold-guard")
    g.add_argument("--repo", default=env.get("GITHUB_REPOSITORY"))
    g.add_argument("--branch", default="docs/steward")
    g.add_argument("--head-branch", default="", help="branch the fold would push (refused if not --branch)")
    n = sub.add_parser("note")
    n.add_argument("--entry", required=True, help="file holding the note block's content, `-` for stdin")
    n.add_argument("--root", default=".")
    a = sub.add_parser("audit")
    a.add_argument("--repo", default=env.get("GITHUB_REPOSITORY"))
    a.add_argument("--report", action="append", default=[], help="NAME=FILE, output of a failed check")
    a.add_argument("--label", default="type: docs")
    a.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)

    def say(line):
        print(line, file=out)

    if args.cmd == "body":
        try:
            result = json.loads(_read(args.pending) or "{}")
        except ValueError as e:
            say(f"✘ {args.pending}: {e}")
            return 2
        folded = [int(n) for n in re.findall(r"\d+", _read(args.folded))] if args.folded else None
        out.write(body(result, folded, _read(args.fold_log), _read(args.unplaced), _read(args.contested)))
        return 0
    if args.cmd == "note":
        placed, message = fold_note(sys.stdin.read() if args.entry == "-" else _read(args.entry), args.root)
        say(message)
        return 0 if placed else 1
    if args.cmd == "fold-guard" and args.head_branch and args.head_branch != args.branch:
        say(f"✘ refused: a fold runs on {args.branch} only, not on {args.head_branch} (one folder at a time)")
        return 1

    if args.cmd == "pending" and (args.branch == args.base or args.branch in args.protected.split()):
        say(f"✘ the steward branch {args.branch} is protected or is the base: it never pushes there")
        return 2
    token = env.get("GH_TOKEN") or env.get("GITHUB_TOKEN")
    if not token and http is None:
        say("⚠ nothing decided: no token (GH_TOKEN or GITHUB_TOKEN)")
        return 2
    if not args.repo:
        say("⚠ nothing decided: no repository (--repo owner/name or GITHUB_REPOSITORY)")
        return 2
    http = http or github(token)
    try:
        if args.cmd in ("fold-guard", "pending"):
            busy = open_fold(args.repo, args.branch, http)
            if busy:
                say(f"✘ refused: fold PR #{busy['number']} from {args.branch} is still open ({busy['url']}); merge or "
                    "close it first, the next pass covers every merge since. Nothing pushed.")
                if args.cmd == "fold-guard":
                    return 1
                if args.json_out:
                    with open(args.json_out, "w", encoding="utf-8") as f:
                        json.dump({"fold": False, "open_fold": busy, "ledger": [], "ledger_order": [], "malformed": [],
                                   "docs": [], "mark_done": []}, f, indent=2)
                return 0
            if args.cmd == "fold-guard":
                say(f"🟢 no open fold PR from {args.branch}: the fold may start")
                return 0
        if args.cmd == "audit":
            reports = {}
            for item in args.report:
                name, _, path = item.partition("=")
                reports[name] = _read(path)
            n = audit(args.repo, reports, args.label, http, args.dry_run, out)
            say(f"{'🟢' if not n else '🟠'} doc audit: {n} issue(s) {'to file' if args.dry_run else 'filed'}")
            return 0
        result = pending(args.repo, args.base, args.branch, args.ledger_label, http,
                         since_days=args.since_days, ledger_heading=args.ledger_heading)
    except FetchError as e:
        say(f"⚠ nothing decided: {e}")
        return 2
    if args.json_out:
        with open(args.json_out, "w", encoding="utf-8") as f:
            json.dump(result, f, indent=2)
    if result["fold"]:
        say(f"🟠 to fold since {result['since']}: ledger {result['ledger'] or 'none'}, "
            f"Docs: lines in {[d['number'] for d in result['docs']] or 'none'}")
    else:
        say(f"🟢 nothing to fold since {result['since']}: no agent started")
    for m in result["malformed"]:
        for problem in m["problems"]:
            say(f"✘ #{m['number']}: malformed ledger entry: {problem}")
    if result["mark_done"]:
        say(f"Folded by the last steward PR, label to swap: {result['mark_done']}")
    return 0


if __name__ == "__main__":
    sys.exit(run())
