class SharedParsingTests(unittest.TestCase):
    def test_gate_uses_the_dashboard_verdict_expressions(self):
        """The verdict format lives in flow-metrics.py only: the gate must not carry its own copy."""
        fm_spec = importlib.util.spec_from_file_location("fm_shared", ROOT / "scripts" / "flow-metrics.py")
        fm = importlib.util.module_from_spec(fm_spec)
        fm_spec.loader.exec_module(fm)
        self.assertEqual(mg.flow.VERDICT_RE.pattern, fm.VERDICT_RE.pattern)
        self.assertEqual(mg.flow.HEAD_RE.pattern, fm.HEAD_RE.pattern)
        source = (ROOT / "scripts" / "merge-gate.py").read_text(encoding="utf-8")
        self.assertNotIn("CHANGES REQUESTED|", source)


