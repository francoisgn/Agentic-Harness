class BodyTests(unittest.TestCase):
    def body_row(self, body, config=None):
        s = state()
        s["pull"]["body"] = body
        return line(gate(s, config=config)[1], "PR body")

    def test_missing_body_lines_are_listed(self):
        row = self.body_row("Some text\nDocs: none\n")
        self.assertTrue(row.startswith("missing"), row)
        for part in ("Closes/Refs", "Claim:", "Docs:"):
            self.assertIn(part, row)

    def test_refs_and_direct_pr_count_as_the_issue_line(self):
        self.assertTrue(self.body_row("Refs #7, left: docs\nClaim: a.b.c\nDocs: README.md\n").startswith("ok"))
        self.assertTrue(self.body_row("Direct-PR: typo\nClaim: a.b.c\nDocs: none (typo)\n").startswith("ok"))

    def test_ledger_section_required_when_the_ledger_is_on(self):
        config = {"ledger": {"enabled": True}}
        row = self.body_row(BODY, config)
        self.assertTrue(row.startswith("missing") and "### Ledger" in row, row)
        with_ledger = "Closes #7\nClaim: a.b.c\n\n### Ledger\n\nDocs: none (refactor)\n"
        self.assertTrue(self.body_row(with_ledger, config).startswith("ok"))

    def test_body_lines_can_be_switched_off(self):
        self.assertIsNone(self.body_row("nothing", {"merge_gate": {"body_lines": []}}))


