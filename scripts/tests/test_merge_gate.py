class OpenQuestionTests(unittest.TestCase):
    def test_unanswered_question_in_the_body_is_missing(self):
        s = state()
        s["pull"]["body"] = BODY.replace("none", "- Should the cache survive a restart?")
        code, out = gate(s)
        self.assertEqual(code, mg.EXIT_NOT_READY)
        self.assertTrue(line(out, "no open question").startswith("missing"), out)

    def test_latest_report_comment_wins_over_the_body(self):
        report = {"body": f"{mg.REPORT_MARKER}\nReport\n\n### Open questions\n\n- Keep v1 format?" + FOOTER,
                  "created_at": "2026-11-10T09:00:00Z", "user": {"login": "x"}}
        newer = {"body": f"{mg.REPORT_MARKER}\nReport\n\n**Open questions**: none.",
                 "created_at": "2026-11-10T09:30:00Z", "user": {"login": "x"}}
        self.assertTrue(line(gate(state(comments=[approval(), report]))[1], "no open question")
                        .startswith("missing"))
        self.assertTrue(line(gate(state(comments=[approval(), report, newer]))[1], "no open question")
                        .startswith("ok"))

    def test_no_report_section_anywhere_leaves_the_line_out(self):
        s = state()
        s["pull"]["body"] = "Closes #7\nClaim: app.orc.lot.7\nDocs: none (refactor)\n"
        code, out = gate(s)
        self.assertEqual(code, mg.EXIT_MAY_MERGE, out)
        self.assertIsNone(line(out, "no open question"))

    def test_report_marker_without_the_section_is_missing(self):
        report = {"body": f"{mg.REPORT_MARKER}\nReport without the section", "created_at": "2026-11-10T09:00:00Z",
                  "user": {"login": "x"}}
        self.assertTrue(line(gate(state(comments=[approval(), report]))[1], "no open question")
                        .startswith("missing"))


